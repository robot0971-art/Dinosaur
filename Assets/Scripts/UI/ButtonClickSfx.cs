// ============================================================
// ButtonClickSfx.cs
// ============================================================
// 이 스크립트가 하는 일:
// 버튼을 클릭하면 효과음을 재생합니다.
// "딸깍" 같은 짧은 클릭 소리를 냅니다.
// 기능 47: 버튼 클릭 효과음
// ============================================================

using UnityEngine;

// ============================================================
// [이 스크립트가 필요한 이유]
// ============================================================
// 버튼을 클릭했을 때 소리가 없으면 클릭한 느낌이 안 납니다.
// 효과음이 있으면 플레이어가 "아, 버튼이 눌렸구나"를 알 수 있습니다.
// ============================================================

// ============================================================
// [어디에 붙이나요?]
// ============================================================
// - 효과음을 내고 싶은 버튼 오브젝트에 붙입니다.
// - 예: 게임 시작 버튼, 게임 종료 버튼, 타이틀 버튼 등
// ============================================================

// ============================================================
// [Inspector에서 연결할 것]
// ============================================================
// - clickSound: 재생할 효과음 파일 (AudioClip)
// - sfxVolume: 효과음 볼륨 (기본값 0.7)
// ============================================================

// ============================================================
// [RequireComponent 설명]
// ============================================================
// 이 스크립트를 붙이면 AudioSource 컴포넌트가 자동으로 추가됩니다.
// Inspector에서 AudioSource를 직접 추가할 필요가 없습니다.
// ============================================================
[RequireComponent(typeof(AudioSource))]
public class ButtonClickSfx : MonoBehaviour
{
    // ============================================================
    // Inspector에서 설정할 변수들
    // ============================================================

    [Header("효과음 설정")]
    [Tooltip("버튼 클릭 시 재생할 효과음 파일을 여기에 연결하세요")]
    [SerializeField] private AudioClip clickSound;

    [Tooltip("효과음 볼륨입니다. 0은 무음, 1은 최대 볼륨입니다")]
    [Range(0f, 1f)]
    [SerializeField] private float sfxVolume = 0.7f;

    // ============================================================
    // 내부 상태 변수
    // ============================================================

    // AudioSource는 소리를 재생하는 Unity 컴포넌트입니다.
    // 스피커 같은 역할을 합니다.
    private AudioSource audioSource;

    // ============================================================
    // Unity 생명주기 함수
    // ============================================================

    /// <summary>
    /// Awake()는 Start()보다 먼저 호출됩니다.
    /// AudioSource 컴포넌트를 가져와서 설정합니다.
    /// </summary>
    private void Awake()
    {
        // RequireComponent로 이미 추가된 AudioSource를 가져옵니다.
        audioSource = GetComponent<AudioSource>();

        // AudioSource 설정을 합니다.
        SetupAudioSource();
    }

    // ============================================================
    // AudioSource 설정 함수
    // ============================================================

    /// <summary>
    /// SetupAudioSource()는 AudioSource의 설정을 구성합니다.
    /// Awake()에서 한 번 호출됩니다.
    /// </summary>
    private void SetupAudioSource()
    {
        // audioSource가 없으면 아무것도 하지 않습니다.
        if (audioSource == null)
        {
            return;
        }

        // playOnAwake를 false로 설정합니다.
        // 씬이 시작될 때 자동으로 재생하지 않겠습니다.
        // 버튼을 클릭할 때만 재생할 것이기 때문입니다.
        audioSource.playOnAwake = false;

        // loop를 false로 설정합니다.
        // 효과음은 한 번만 재생하면 됩니다.
        // 반복 재생하지 않습니다.
        audioSource.loop = false;
    }

    // ============================================================
    // 공개 함수
    // ============================================================

    /// <summary>
    /// PlayClickSound()는 버튼 클릭 효과음을 재생합니다.
    /// Button 컴포넌트의 OnClick에 연결해서 사용합니다.
    /// 
    /// [사용 방법]
    /// 1. Inspector에서 Button 컴포넌트의 OnClick()을 찾습니다.
    /// 2. + 버튼을 클릭합니다.
    /// 3. 이 오브젝트를 연결합니다.
    /// 4. 함수를 ButtonClickSfx → PlayClickSound()로 선택합니다.
    /// </summary>
    public void PlayClickSound()
    {
        // audioSource가 없으면 아무것도 하지 않습니다.
        if (audioSource == null)
        {
            return;
        }

        // 효과음 파일이 연결되지 않았으면 경고를 표시합니다.
        if (clickSound == null)
        {
            Debug.LogWarning("[ButtonClickSfx] 효과음 파일이 연결되지 않았습니다. Inspector에서 Click Sound를 연결하세요.");
            return;
        }

        // 효과음을 한 번 재생합니다.
        // PlayOneShot은 같은 소리를 겹쳐서 재생할 수 있습니다.
        // Play()보다 효과음 재생에 더 적합합니다.
        audioSource.PlayOneShot(clickSound, sfxVolume);
    }
}
