// ============================================================
// InGameButtonClickSfx.cs
// ============================================================
// 이 스크립트가 하는 일:
// 인게임 UI 버튼을 클릭했을 때 "딸깍" 같은 짧은 효과음을 재생합니다.
// 기능 55: 버튼 클릭 효과음 (인게임)
// ============================================================

using UnityEngine;

// ============================================================
// [이 스크립트가 필요한 이유]
// ============================================================
// 게임 중 버튼을 눌렀을 때 아무 소리가 없으면 눌린 느낌이 약합니다.
// 클릭 효과음이 있으면 플레이어가 버튼 입력을 더 확실하게 느낄 수 있습니다.
// ============================================================

// ============================================================
// [어디에 붙이나요?]
// ============================================================
// - GameSceneUI 씬의 ResumeButton 같은 인게임 버튼에 붙입니다.
// - GameOver 씬의 RestartButton, TitleButton, QuitButton에도 붙일 수 있습니다.
// ============================================================

// ============================================================
// [Inspector에서 연결할 것]
// ============================================================
// - clickSound: 재생할 버튼 클릭 효과음 파일 (AudioClip)
// - sfxVolume: 효과음 볼륨 (기본값 0.7)
// ============================================================

// 이 스크립트를 붙이면 AudioSource가 자동으로 같이 붙습니다.
// AudioSource는 Unity에서 소리를 재생하는 스피커 같은 컴포넌트입니다.
[RequireComponent(typeof(AudioSource))]
public class InGameButtonClickSfx : MonoBehaviour
{
    // ============================================================
    // Inspector에서 설정할 변수들
    // ============================================================

    [Header("인게임 버튼 클릭 효과음 설정")]
    [Tooltip("인게임 버튼 클릭 시 재생할 효과음 파일을 연결하세요")]
    [SerializeField] private AudioClip clickSound;

    [Tooltip("효과음 볼륨입니다. 0은 무음, 1은 최대 볼륨입니다. 기본값 0.7")]
    [Range(0f, 1f)]
    [SerializeField] private float sfxVolume = 0.7f;

    // ============================================================
    // 내부 상태 변수
    // ============================================================

    // 실제로 소리를 재생하는 AudioSource입니다.
    private AudioSource audioSource;

    // ============================================================
    // Unity 생명주기 함수
    // ============================================================

    /// <summary>
    /// Awake()는 Start()보다 먼저 호출됩니다.
    /// AudioSource를 가져오고 기본 설정을 합니다.
    /// </summary>
    private void Awake()
    {
        // 같은 오브젝트에 붙어 있는 AudioSource를 가져옵니다.
        audioSource = GetComponent<AudioSource>();

        // 버튼 클릭 효과음용으로 AudioSource를 설정합니다.
        SetupAudioSource();
    }

    // ============================================================
    // AudioSource 설정 함수
    // ============================================================

    /// <summary>
    /// SetupAudioSource()는 AudioSource의 기본 설정을 합니다.
    /// </summary>
    private void SetupAudioSource()
    {
        if (audioSource == null)
        {
            return;
        }

        // 버튼 클릭 전에는 자동으로 소리가 나면 안 되므로 꺼둡니다.
        audioSource.playOnAwake = false;

        // 클릭 효과음은 한 번만 나야 하므로 반복 재생을 끕니다.
        audioSource.loop = false;
    }

    // ============================================================
    // 공개 함수
    // ============================================================

    /// <summary>
    /// PlayClickSound()는 버튼 클릭 효과음을 한 번 재생합니다.
    /// Button 컴포넌트의 OnClick()에 연결해서 사용합니다.
    /// </summary>
    public void PlayClickSound()
    {
        if (audioSource == null)
        {
            return;
        }

        if (clickSound == null)
        {
            Debug.LogWarning("[InGameButtonClickSfx] 효과음 파일이 연결되지 않았습니다. Inspector에서 Click Sound를 연결하세요.", this);
            return;
        }

        // PlayOneShot은 짧은 효과음을 한 번 재생할 때 사용하기 좋습니다.
        audioSource.PlayOneShot(clickSound, sfxVolume);
    }
}
