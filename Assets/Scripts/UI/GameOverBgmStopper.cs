// 이 스크립트가 하는 일:
// GameOver 씬이 로드되면 게임 배경음악을 자동으로 멈춥니다.
// GameBgmPlayer.Instance를 찾아서 StopBgm()을 호출합니다.
// Inspector에서 연결할 필요가 없습니다.
// ============================================================

using UnityEngine;

// ============================================================
// [이 스크립트가 필요한 이유]
// ============================================================
// GameSceneUI 씬과 GameOver 씬은 서로 다른 씬입니다.
// 다른 씬의 오브젝트를 Inspector에 연결할 수 없기 때문에
// 코드에서 자동으로 GameBgmPlayer를 찾아서 멈춥니다.
// ============================================================

// ============================================================
// [어디에 붙이나요?]
// ============================================================
// - GameOver 씬의 빈 오브젝트에 붙입니다.
// - 오브젝트 이름: GameOverBgmStopper
// - Inspector에서 연결할 것이 없습니다.
// ============================================================

public class GameOverBgmStopper : MonoBehaviour
{
    /// <summary>
    /// Start()는 씬이 시작될 때 한 번 호출됩니다.
    /// GameBgmPlayer를 찾아서 배경음악을 멈춥니다.
    /// </summary>
    private void Start()
    {
        // GameBgmPlayer.Instance가 있으면 배경음악을 멈춥니다.
        // GameBgmPlayer는 DontDestroyOnLoad로 씬 전환 시에도 유지됩니다.
        // 그래서 GameOver 씬에서도 Instance로 접근할 수 있습니다.
        if (GameBgmPlayer.Instance != null)
        {
            GameBgmPlayer.Instance.StopBgm();
        }
    }
}
