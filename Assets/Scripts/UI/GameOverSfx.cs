// ============================================================
// GameOverSfx.cs
// ============================================================
// 이 스크립트가 하는 일:
// GameOver 씬이 시작되면 "꽝" 또는 "쿵" 같은 게임오버 효과음을
// 한 번만 재생합니다.
// 기능 53: 게임오버 효과음
// ============================================================

using UnityEngine;

// ============================================================
// [이 스크립트가 필요한 이유]
// ============================================================
// 게임오버 화면으로 넘어갔을 때 아무 소리도 없으면 실패한 느낌이 약합니다.
// 무거운 충돌음이 한 번 재생되면 "아, 게임오버가 됐구나"를
// 플레이어가 더 확실하게 느낄 수 있습니다.
// ============================================================

// ============================================================
// [어디에 붙이나요?]
// ============================================================
// - GameOver 씬의 빈 오브젝트에 붙입니다.
// - 오브젝트 이름 추천: GameOverSfx
// - GameSceneUI가 아니라 GameOver 씬에서 설정합니다.
// ============================================================

// ============================================================
// [Inspector에서 연결할 것]
// ============================================================
// - gameOverSound: 재생할 게임오버 효과음 파일 (AudioClip)
// - sfxVolume: 효과음 볼륨 (기본값 0.8)
// ============================================================

// 이 스크립트를 붙이면 AudioSource가 자동으로 같이 붙습니다.
// AudioSource는 Unity에서 소리를 재생하는 스피커 같은 컴포넌트입니다.
[RequireComponent(typeof(AudioSource))]
public class GameOverSfx : MonoBehaviour
{
    // ============================================================
    // Inspector에서 설정할 변수들
    // ============================================================

    [Header("게임오버 효과음 설정")]
    [Tooltip("GameOver 씬이 시작될 때 한 번 재생할 효과음 파일을 연결하세요")]
    [SerializeField] private AudioClip gameOverSound;

    [Tooltip("효과음 볼륨입니다. 0은 무음, 1은 최대 볼륨입니다. 기본값 0.8")]
    [Range(0f, 1f)]
    [SerializeField] private float sfxVolume = 0.8f;

    // ============================================================
    // 내부 상태 변수
    // ============================================================

    // 실제로 소리를 재생하는 AudioSource입니다.
    private AudioSource audioSource;

    // ============================================================
    // Unity 생명주기 함수
    // ============================================================

    /// <summary>
    /// Awake()는 Start()보다 먼저 호출됩니다.
    /// AudioSource를 가져오고 기본 설정을 합니다.
    /// </summary>
    private void Awake()
    {
        // 같은 오브젝트에 붙어 있는 AudioSource를 가져옵니다.
        audioSource = GetComponent<AudioSource>();

        // AudioSource를 게임오버 효과음용으로 설정합니다.
        SetupAudioSource();
    }

    /// <summary>
    /// Start()는 씬이 시작될 때 한 번 호출됩니다.
    /// GameOver 씬에 들어오면 효과음을 한 번 재생합니다.
    /// </summary>
    private void Start()
    {
        PlayGameOverSound();
    }

    // ============================================================
    // AudioSource 설정 함수
    // ============================================================

    /// <summary>
    /// SetupAudioSource()는 AudioSource의 기본 설정을 합니다.
    /// </summary>
    private void SetupAudioSource()
    {
        if (audioSource == null)
        {
            return;
        }

        // 효과음은 씬 시작 시 Start()에서 직접 재생할 것이므로 자동 재생은 끕니다.
        audioSource.playOnAwake = false;

        // 게임오버 효과음은 한 번만 재생해야 하므로 반복 재생을 끕니다.
        audioSource.loop = false;
    }

    // ============================================================
    // 공개 함수
    // ============================================================

    /// <summary>
    /// PlayGameOverSound()는 게임오버 효과음을 한 번 재생합니다.
    /// Button OnClick 테스트에도 연결할 수 있습니다.
    /// </summary>
    public void PlayGameOverSound()
    {
        if (audioSource == null)
        {
            return;
        }

        if (gameOverSound == null)
        {
            Debug.LogWarning("[GameOverSfx] 효과음 파일이 연결되지 않았습니다. Inspector에서 Game Over Sound를 연결하세요.", this);
            return;
        }

        // PlayOneShot은 효과음을 한 번 재생할 때 사용하기 좋은 함수입니다.
        audioSource.PlayOneShot(gameOverSound, sfxVolume);
    }
}
